export type PackingItem = { id: string; label: string };
export type PackingCategory = { title: string; items: PackingItem[] };

// IDs are derived from the category + item text (not array indexes), so editing
// or reordering the list later never shifts saved check marks onto the wrong item.
export const CATEGORIES: PackingCategory[] = Object.entries(PACKING_LIST).map(
  ([title, items]) => ({
    title,
    items: items.map((label) => ({ id: `${title}::${label}`, label })),
  }),
);

export const TOTAL_ITEMS = CATEGORIES.reduce((sum, c) => sum + c.items.length, 0);
